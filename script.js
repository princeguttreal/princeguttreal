// Fluid scroll reveals: one observer, staggered entrances and reduced-motion support.
const motionTargets=document.querySelectorAll('.section-kicker,.intro-grid>*,.services-head>*,.service-list article,.equipment-head>*,.equipment-grid>div,.portfolio-head>*,.case-card,.contact-layout>*');
const reduceMotion=window.matchMedia('(prefers-reduced-motion: reduce)').matches;
if(!reduceMotion&&'IntersectionObserver' in window){
  const revealObserver=new IntersectionObserver((entries,observer)=>{
    entries.forEach(entry=>{
      if(entry.isIntersecting){entry.target.classList.add('is-visible');observer.unobserve(entry.target);}
    });
  },{threshold:.12,rootMargin:'0px 0px -45px 0px'});
  motionTargets.forEach((element,index)=>{
    element.classList.add('reveal');
    const group=element.parentElement;
    const siblings=[...group.children].filter(item=>item.matches('.reveal'));
    element.style.setProperty('--reveal-delay',(Math.min(siblings.length-1,4)*85)+'ms');
    revealObserver.observe(element);
  });
}else{
  motionTargets.forEach(element=>element.classList.add('is-visible'));
}


// Instagram feed: reads the five latest posts generated by the scheduled GitHub Action.
const instagramTrack=document.querySelector('#instagram-track');
const instagramStatus=document.querySelector('#instagram-feed-status');
if(instagramTrack){
  const safeHttpsUrl=(value)=>{try{const url=new URL(value);return url.protocol==='https:'?url.href:null;}catch{return null;}};
  const dateLabel=(value)=>{const date=new Date(value);return Number.isNaN(date.getTime())?'':new Intl.DateTimeFormat('pt-BR',{day:'2-digit',month:'short',year:'numeric'}).format(date).replace('.','').toUpperCase();};
  const showInstagramEmpty=(message)=>{instagramTrack.replaceChildren();const empty=document.createElement('div');empty.className='instagram-empty';empty.textContent=message+' ';const link=document.createElement('a');link.href='https://www.instagram.com/princeguttreal/';link.target='_blank';link.rel='noopener noreferrer';link.textContent='Ver @princeguttreal no Instagram ↗';empty.append(link);instagramTrack.append(empty);};
  const makeInstagramCard=(post)=>{
    const permalink=safeHttpsUrl(post.permalink);const imageUrl=safeHttpsUrl(post.thumbnail_url||post.media_url);
    if(!permalink||!imageUrl)return null;
    const article=document.createElement('article');article.className='instagram-card';
    const link=document.createElement('a');link.className='instagram-card-link';link.href=permalink;link.target='_blank';link.rel='noopener noreferrer';link.setAttribute('aria-label','Abrir publicação no Instagram');
    const media=document.createElement('div');media.className='instagram-card-media';
    const img=document.createElement('img');img.src=imageUrl;img.alt='Publicação recente de @princeguttreal';img.loading='lazy';img.decoding='async';img.onerror=()=>{article.remove();};media.append(img);
    const type=document.createElement('span');type.className='instagram-card-type';type.textContent=post.media_type==='VIDEO'?'VÍDEO':post.media_type==='CAROUSEL_ALBUM'?'CARROSSEL':'INSTAGRAM';media.append(type);
    const open=document.createElement('span');open.className='instagram-card-open';open.setAttribute('aria-hidden','true');open.textContent='↗';media.append(open);
    const copy=document.createElement('div');copy.className='instagram-card-copy';
    const caption=document.createElement('p');caption.textContent=post.caption||'Confira esta publicação no Instagram.';copy.append(caption);
    const time=document.createElement('time');time.dateTime=post.timestamp||'';time.textContent=dateLabel(post.timestamp);copy.append(time);
    link.append(media,copy);article.append(link);return article;
  };
  fetch('instagram-feed.json?update='+Date.now(),{cache:'no-store'})
    .then(response=>{if(!response.ok)throw new Error('Feed indisponível');return response.json();})
    .then(feed=>{
      const posts=Array.isArray(feed.posts)?feed.posts.slice(0,5):[];
      const cards=posts.map(makeInstagramCard).filter(Boolean);
      instagramTrack.replaceChildren();
      if(!cards.length){showInstagramEmpty('A integração está preparada. Assim que a conexão oficial com a Meta for ativada, suas cinco publicações mais recentes aparecerão aqui.');return;}
      cards.forEach(card=>instagramTrack.append(card));
      if(instagramStatus&&feed.updated_at){instagramStatus.textContent='FEED SINCRONIZADO · '+dateLabel(feed.updated_at);}
    })
    .catch(()=>showInstagramEmpty('Não foi possível carregar o feed agora.'));
  document.querySelectorAll('[data-instagram-direction]').forEach(button=>button.addEventListener('click',()=>{
    const direction=Number(button.dataset.instagramDirection)||1;
    instagramTrack.scrollBy({left:direction*Math.max(260,instagramTrack.clientWidth*.82),behavior:window.matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth'});
  }));
}
